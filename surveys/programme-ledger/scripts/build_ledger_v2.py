"""Programme ledger v2 — merge the per-report harvest into one table plus
the shared Constraint / AnalysisRun / Candidate records (plan goal 5).

Inputs:  surveys/programme-ledger/harvest/*.yaml            transcribed rows (tracked; see harvest/SCHEMA.md)
         runs/programme-ledger/v2/harvest_generated/*.yaml  per-record Pipeline A rows (scripts/harvest/pipeline_a_*.py)
Outputs: runs/programme-ledger/v2/programme_ledger_v2.ecsv               full table (28k rows)
         surveys/programme-ledger/results/programme_ledger_v2_crossings.ecsv  Pipeline B + programme-wide rows (tracked)
         surveys/programme-ledger/results/programme_ledger_v2_summary.json
         surveys/programme-ledger/results/programme_ledger_v2_matrix.json
         runs/programme-ledger/v2/records/{analysis_run,constraint,candidate}.jsonl
         runs/programme-ledger/v2/manifest.json

The ledger is an index of what the reports state; it never re-derives a
limit. Every row carries the report/results citation it came from.

Usage: uv run python surveys/programme-ledger/scripts/build_ledger_v2.py
"""
